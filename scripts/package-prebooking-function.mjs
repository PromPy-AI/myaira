import {readFile, mkdir, writeFile} from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const core = await readFile(new URL('supabase/functions/aira-prebook/core.ts', root), 'utf8');
const entry = await readFile(new URL('supabase/functions/aira-prebook/index.ts', root), 'utf8');
const body = entry.replace(/^import \{[\s\S]*?\} from "\.\/core\.ts";\r?\n/, '');
if (body === entry) throw new Error('Unexpected entrypoint import; check bundling before deployment.');
await mkdir(new URL('supabase/dashboard/', root), {recursive:true});
await writeFile(new URL('supabase/dashboard/aira-prebook.ts', root),
  '// Generated by scripts/package-prebooking-function.mjs. Edit the source files, not this copy.\n' +
  '// Deploy as aira-prebook. Custom authentication requires verify_jwt=false.\n' + core + '\n' + body);
console.log('Prepared supabase/dashboard/aira-prebook.ts');
